Коды выхода

  0. Истина/успех
  1. Ложь/общая ошибка
  2. Неверный синтаксис команды
  3. Отсутствует бинарный файл busybox
  4. Запущено не от имени суперпользователя
  5. Доступно обновление ("--upgrade")
  6. Обновление недоступно ("--upgrade")
  7. Не удалось остановить зарядку
  8. Демон уже запущен ("--daemon start")
  9. Демон не запущен ("--daemon" и "--daemon stop")
  10. Не сработал ни один переключатель зарядки (--test)
  11. Ток (мА) не находится в диапазоне от 0 до 9999
  12. Не удалось выполнить инициализацию
  13. Не удалось установить блокировку $TMPDIR/acc.lock
  14. ACC не может инициализироваться, так как установлен флаг "disable"
  15. Режим питания от зарядного устройства поддерживается (--test)
  16. Не удалось включить зарядку (--test)

  Журналы автоматически экспортируются ("--log --export") при кодах выхода 1, 2 и 7.


Советы

  Команды можно объединять в цепочки для расширения функциональности.
    например, заряжать 30 минут, отключить зарядку на 6 часов, зарядить до 85% и перезапустить демон
    acc -e 30m && acc -d 6h && acc -e 85 && accd

  Для расписания профилей можно использовать однострочные скрипты и встроенную функцию "at" (см. -c|--config).

  Пример профиля
    acc -s pc=60 mcc=500 mcv=3900
      Уровень заряда батареи будет поддерживаться в диапазоне 55-60%, ток зарядки ограничится до 500 мА, а напряжение — до 3900 милливольт.
      Подходит для ночной зарядки и постоянного подключения к зарядному устройству.

  Полная документация приведена в acc -r (или --readme) (рекомендуется)
EOF
